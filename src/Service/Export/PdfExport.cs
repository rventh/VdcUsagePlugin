using MyPlugin.Service.Usage;
using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;

namespace MyPlugin.Service.Export;

/// <summary>
/// Dependency-free PDF writer. The layout follows the VSPC "License Usage" report: a light title, a Parameters block with blue section rules,
/// one section per tenant, and a footer with the creation time and page numbers.
/// </summary>
public static class PdfExport
{
    private const double PageW = 595, PageH = 842, Margin = 40, RowH = 14, Bottom = 56;
    private const double Right = PageW - Margin;
    private const string Blue = "0.04 0.35 0.56";
    private const string Ink = "0.13 g";
    private const string Muted = "0.40 g";

    private sealed class Page
    {
        public StringBuilder Content { get; } = new();
    }

    public static byte[] Build(IReadOnlyList<UsageRow> rows, IReadOnlyList<string> filterLines, string generatedBy)
    {
        var pages = new List<Page>();
        var now = DateTime.Now;
        var generated = now.ToString("d/M/yyyy h:mm:ss tt", CultureInfo.InvariantCulture);
        var zone = Clean(TimeZoneInfo.Local.DisplayName, 60);

        var page = NewPage(pages);
        var y = PageH - Margin - 24;
        Action? redraw = null;

        void EnsureSpace(double needed)
        {
            if (y - needed >= Bottom)
            {
                return;
            }

            page = NewPage(pages);
            y = PageH - Margin;
            redraw?.Invoke();
        }

        void Section(string title)
        {
            redraw = null;
            EnsureSpace(80);
            Text(page, Margin, y, 10, Clean(title, 90), bold: true, color: Ink);
            Rule(page, Margin, Right, y - 5);
            y -= 22;
        }

        // title block
        Text(page, Margin, y, 22, "License Usage", color: "0.20 g");
        TextRight(page, Right, y + 2, 13, "VDC Usage", bold: true, color: Blue + " rg");
        y -= 34;

        // parameters
        var tenantNames = rows.Select(r => r.TenantName).Distinct(StringComparer.OrdinalIgnoreCase).OrderBy(n => n, StringComparer.OrdinalIgnoreCase).ToList();
        var months = rows.Select(r => r.Month).Where(m => !string.IsNullOrEmpty(m)).Distinct().OrderBy(m => m, StringComparer.Ordinal).ToList();
        var interval = "-";
        if (months.Count > 0
            && DateTime.TryParseExact(months[0] + "-01", "yyyy-MM-dd", CultureInfo.InvariantCulture, DateTimeStyles.None, out var first)
            && DateTime.TryParseExact(months[months.Count - 1] + "-01", "yyyy-MM-dd", CultureInfo.InvariantCulture, DateTimeStyles.None, out var last))
        {
            interval = first.ToString("d/M/yyyy", CultureInfo.InvariantCulture) + " - " + last.AddMonths(1).AddDays(-1).ToString("d/M/yyyy", CultureInfo.InvariantCulture);
        }

        var tenantText = tenantNames.Count == 0 ? "None" : tenantNames.Count <= 3 ? string.Join(", ", tenantNames) : tenantNames.Count + " tenants";
        var filters = filterLines.Where(l => !l.StartsWith("Months:", StringComparison.Ordinal) && !l.StartsWith("Filters:", StringComparison.Ordinal)).ToList();

        Section("Parameters");
        void Param(string label, string value)
        {
            EnsureSpace(RowH + 4);
            Text(page, Margin + 5, y, 9, label, color: Muted);
            Text(page, 190, y, 9, Clean(value, 95), color: Ink);
            y -= RowH + 4;
        }

        Param("Tenants:", tenantText);
        Param("Reporting Interval:", interval);
        Param("Generation Date:", now.ToString("d/M/yyyy", CultureInfo.InvariantCulture));
        Param("Generated by:", string.IsNullOrWhiteSpace(generatedBy) ? "-" : generatedBy);
        if (filters.Count == 0)
        {
            Param("Filters:", "None");
        }
        else
        {
            for (var i = 0; i < filters.Count; i++)
            {
                Param(i == 0 ? "Filters:" : string.Empty, filters[i]);
            }
        }

        y -= 6;
        if (rows.Count == 0)
        {
            Section("No data available");
        }
        else
        {
            // summary by product family
            Section("Summary");
            void SummaryHeader()
            {
                TableHead(page, y, ("Product family", Margin + 5, false), ("Tenants", 400, true), ("Points", Right - 5, true));
                y -= RowH + 2;
            }

            redraw = SummaryHeader;
            SummaryHeader();
            foreach (var g in rows.GroupBy(x => x.Family).OrderByDescending(x => x.Sum(y2 => y2.Points)))
            {
                EnsureSpace(RowH);
                Text(page, Margin + 5, y, 8.5, Clean(g.Key, 60), color: Ink);
                TextRight(page, 400, y, 8.5, g.Select(x => x.TenantUid).Distinct().Count().ToString(CultureInfo.InvariantCulture), color: Ink);
                TextRight(page, Right - 5, y, 8.5, Fmt(g.Sum(x => x.Points)), color: Ink);
                y -= RowH;
            }

            EnsureSpace(RowH + 6);
            Rule(page, Margin, Right, y + 9, 0.4);
            Text(page, Margin + 5, y - 2, 9, "Total points", bold: true, color: Ink);
            TextRight(page, Right - 5, y - 2, 9, Fmt(rows.Sum(r => r.Points)), bold: true, color: Ink);
            y -= RowH + 14;

            // one section per tenant
            foreach (var tenant in rows.GroupBy(x => x.TenantName).OrderBy(x => x.Key, StringComparer.OrdinalIgnoreCase))
            {
                var company = tenant.First().CompanyName;
                Section(company.Length > 0 && !company.Equals(tenant.Key, StringComparison.OrdinalIgnoreCase) ? $"{tenant.Key}  ({company})" : tenant.Key);
                void DetailHeader()
                {
                    TableHead(page, y, ("Month", Margin + 5, false), ("Product", 100, false), ("Edition", 200, false), ("Cloud", 290, false), ("Region", 335, false), ("Used", 465, true), ("Points", Right - 5, true));
                    y -= RowH + 2;
                }

                redraw = DetailHeader;
                DetailHeader();
                foreach (var r in tenant.OrderBy(x => x.Month, StringComparer.Ordinal).ThenBy(x => x.SkuName, StringComparer.OrdinalIgnoreCase))
                {
                    EnsureSpace(RowH);
                    Text(page, Margin + 5, y, 8.5, MonthFormat.Label(r.Month), color: Ink);
                    Text(page, 100, y, 8.5, Clean(r.Family, 22), color: Ink);
                    Text(page, 200, y, 8.5, Clean(r.Edition, 18), color: Ink);
                    Text(page, 290, y, 8.5, Clean(r.Cloud, 8), color: Muted);
                    Text(page, 335, y, 8.5, Clean(r.RegionType, 10), color: Muted);
                    TextRight(page, 465, y, 8.5, UnitFormat.Label(r.UsedUnits, r.UnitType), color: Ink);
                    TextRight(page, Right - 5, y, 8.5, Fmt(r.Points), color: Ink);
                    y -= RowH;
                }

                EnsureSpace(RowH + 6);
                Rule(page, 335, Right, y + 9, 0.4);
                Text(page, 335, y - 2, 9, "Total", bold: true, color: Ink);
                TextRight(page, Right - 5, y - 2, 9, Fmt(tenant.Sum(r => r.Points)), bold: true, color: Ink);
                y -= RowH + 16;
            }
        }

        // footer on every page
        for (var i = 0; i < pages.Count; i++)
        {
            Text(pages[i], Margin, 28, 8, $"Report created: {generated} {zone}", color: Muted);
            TextRight(pages[i], Right, 28, 8, $"{i + 1} of {pages.Count}", color: Muted);
        }

        return Assemble(pages);
    }

    private static void Rule(Page p, double x1, double x2, double y, double width = 0.9)
    {
        p.Content.Append($"{Blue} RG {Num(width)} w {Num(x1)} {Num(y)} m {Num(x2)} {Num(y)} l S\n");
    }

    private static void TableHead(Page p, double y, params (string Title, double X, bool RightAligned)[] cols)
    {
        foreach (var c in cols)
        {
            if (c.RightAligned)
            {
                TextRight(p, c.X, y, 8, c.Title, bold: true, color: Muted);
            }
            else
            {
                Text(p, c.X, y, 8, c.Title, bold: true, color: Muted);
            }
        }

        p.Content.Append($"0.80 G 0.4 w {Num(Margin)} {Num(y - 4)} m {Num(Right)} {Num(y - 4)} l S\n");
    }

    private static Page NewPage(List<Page> pages)
    {
        var p = new Page();
        pages.Add(p);
        return p;
    }

    private static double Width(string text, double size, bool bold)
    {
        var w = 0d;
        foreach (var ch in text)
        {
            w += char.IsDigit(ch) ? 0.556 : (ch is ',' or '.' or ' ' or ':' or '-' or 'i' or 'l' or 'I' or 'j' or '(' or ')') ? 0.30 : char.IsUpper(ch) ? 0.67 : 0.52;
        }

        return w * size * (bold ? 1.06 : 1.0);
    }

    private static void TextRight(Page p, double right, double y, double size, string text, bool bold = false, string color = Ink)
    {
        Text(p, right - Width(text, size, bold), y, size, text, bold, color);
    }

    private static void Text(Page p, double x, double y, double size, string text, bool bold = false, string color = Ink)
    {
        p.Content.Append($"{color} BT /{(bold ? "F2" : "F1")} {Num(size)} Tf {Num(x)} {Num(y)} Td ({Escape(text)}) Tj ET\n");
    }

    private static string Escape(string s) => s.Replace("\\", "\\\\").Replace("(", "\\(").Replace(")", "\\)");

    private static string Clean(string s, int max)
    {
        var sb = new StringBuilder();
        foreach (var ch in s ?? string.Empty)
        {
            sb.Append(ch >= 32 && ch < 127 ? ch : '?');
        }

        var t = sb.ToString();
        return t.Length <= max ? t : t.Substring(0, Math.Max(0, max - 1)) + "~";
    }

    private static string Fmt(double v) => v.ToString("#,0.##", CultureInfo.InvariantCulture);
    private static string Num(double v) => v.ToString("0.##", CultureInfo.InvariantCulture);

    private static byte[] Assemble(List<Page> pages)
    {
        // object numbers: 1 catalog, 2 pages, 3 font regular, 4 font bold, then (page, content) pairs
        var objects = new List<string>();
        var kids = new StringBuilder();
        for (var i = 0; i < pages.Count; i++)
        {
            kids.Append($"{5 + i * 2} 0 R ");
        }

        objects.Add("<< /Type /Catalog /Pages 2 0 R >>");
        objects.Add($"<< /Type /Pages /Kids [{kids}] /Count {pages.Count} >>");
        objects.Add("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>");
        objects.Add("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>");
        for (var i = 0; i < pages.Count; i++)
        {
            var contentId = 6 + i * 2;
            objects.Add($"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {PageW} {PageH}] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents {contentId} 0 R >>");
            var content = pages[i].Content.ToString();
            objects.Add($"<< /Length {Encoding.ASCII.GetByteCount(content)} >>\nstream\n{content}endstream");
        }

        using var ms = new MemoryStream();
        void Write(string s) { var b = Encoding.ASCII.GetBytes(s); ms.Write(b, 0, b.Length); }

        Write("%PDF-1.4\n");
        var offsets = new List<long>();
        for (var i = 0; i < objects.Count; i++)
        {
            offsets.Add(ms.Position);
            Write($"{i + 1} 0 obj\n{objects[i]}\nendobj\n");
        }

        var xref = ms.Position;
        Write($"xref\n0 {objects.Count + 1}\n0000000000 65535 f \n");
        foreach (var o in offsets)
        {
            Write(o.ToString("0000000000", CultureInfo.InvariantCulture) + " 00000 n \n");
        }

        Write($"trailer\n<< /Size {objects.Count + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n");
        return ms.ToArray();
    }
}
